export type TranslationKey = keyof typeof TRANSLATIONS.en;

interface LanguageContextValue {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: TranslationKey) => string;
  navLabel: (section: NavSection) => string;
  sectionTitle: (section: NavSection) => string;
  statusLabel: (status: VehicleStatus) => string;
  ownershipLabel: (ownership: VehicleOwnership) => string;
  categoryLabel: (category: ExpenseCategory) => string;
  reportLabel: (type: ReportType) => string;
  paymentMethodLabel: (method: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function getInitialLanguage(): Language {
  try {
    const saved = window.localStorage.getItem(LANG_STORAGE_KEY);
    if (saved === 'en' || saved === 'so') return saved;
  } catch {
    // Ignore storage access errors
  }
  return 'so'; // Default language: Somali
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(getInitialLanguage);

  const setLang = (next: Language) => {
    setLangState(next);
    try {
      window.localStorage.setItem(LANG_STORAGE_KEY, next);
    } catch {
      // Ignore
    }
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key: TranslationKey): string => TRANSLATIONS[lang][key] ?? TRANSLATIONS.en[key];

  const navLabel = (section: NavSection): string => {
    const map: Record<NavSection, TranslationKey> = {
      dashboard: 'nav_dashboard',
      vehicles: 'nav_vehicles',
      'daily-work': 'nav_daily_work',
      expenses: 'nav_expenses',
      'rental-payments': 'nav_rental_payments',
      reports: 'nav_reports',
      settings: 'nav_settings',
    };
    return t(map[section]);
  };

  const sectionTitle = (section: NavSection): string => {
    const map: Record<NavSection, TranslationKey> = {
      dashboard: 'section_dashboard',
      vehicles: 'section_vehicles',
      'daily-work': 'section_daily_work',
      expenses: 'section_expenses',
      'rental-payments': 'section_rental_payments',
      reports: 'section_reports',
      settings: 'section_settings',
    };
    return t(map[section]);
  };

  const statusLabel = (status: VehicleStatus): string => {
    if (status === 'Active') return t('statusActive');
    if (status === 'Maintenance') return t('statusMaintenance');
    return t('statusInactive');
  };

  const ownershipLabel = (ownership: VehicleOwnership): string =>
    ownership === 'rented' ? t('rented') : t('companyOwned');

  const categoryLabel = (category: ExpenseCategory): string => {
    const map: Record<ExpenseCategory, TranslationKey> = {
      Fuel: 'cat_Fuel',
      Food: 'cat_Food',
      Maintenance: 'cat_Maintenance',
      'Road fees': 'cat_Road_fees',
      'Loading and unloading': 'cat_Loading_and_unloading',
      'Driver allowance': 'cat_Driver_allowance',
      'Other expenses': 'cat_Other_expenses',
    };
    return t(map[category] ?? 'cat_Other_expenses');
  };

  const reportLabel = (type: ReportType): string => {
    const map: Record<ReportType, TranslationKey> = {
      daily: 'rep_daily',
      weekly: 'rep_weekly',
      monthly: 'rep_monthly',
      vehicle_income: 'rep_vehicle_income',
      expense: 'rep_expense',
      rental_payment: 'rep_rental_payment',
    };
    return t(map[type]);
  };

  const paymentMethodLabel = (method: string): string => {
    if (method === 'Cash') return t('methodCash');
    if (method === 'Bank Transfer') return t('methodBank');
    if (method === 'Mobile Money') return t('methodMobile');
    if (method === 'Check') return t('methodCheck');
    return method;
  };

  return (
    <LanguageContext.Provider
      value={{
        lang,
        setLang,
        t,
        navLabel,
        sectionTitle,
        statusLabel,
        ownershipLabel,
        categoryLabel,
        reportLabel,
        paymentMethodLabel,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage(): LanguageContextValue {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error('useLanguage must be used within LanguageProvider');
  }
  return ctx;
}
